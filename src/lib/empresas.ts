const SOBRA = new Set(["SA", "SAS", "LTDA", "LIMITADA", "EU", "SSA", "AS", "SS"]);

function tokens(value: string) {
  return value
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toUpperCase()
    .replace(/&/g, " Y ")
    .replace(/\bS\.?\s*A\.?\s*S\.?\b/g, " ")
    .replace(/\bS\.?\s*S\.?\s*A\.?\b/g, " ")
    .replace(/\bS\.?\s*A\.?\b/g, " ")
    .replace(/\bLTDA\b/g, " ")
    .replace(/\bLIMITADA\b/g, " ")
    .replace(/[^A-Z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .filter((t) => t && !SOBRA.has(t));
}

function dist(a: string, b: string) {
  const filas = Array.from({ length: a.length + 1 }, (_, i) => [i]);
  for (let j = 0; j <= b.length; j += 1) filas[0][j] = j;
  for (let i = 1; i <= a.length; i += 1) {
    for (let j = 1; j <= b.length; j += 1) {
      filas[i][j] = Math.min(filas[i - 1][j] + 1, filas[i][j - 1] + 1, filas[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
  }
  return filas[a.length][b.length];
}

function cerca(a: string, b: string) {
  if (a === b) return true;
  if (Math.abs(a.length - b.length) > 2) return false;
  if (a.length >= 4 && (a.startsWith(b) || b.startsWith(a))) return true;
  return dist(a, b) <= 1;
}

export function unificarEmpresa(value: string) {
  const escrito = value.trim().replace(/\s+/g, " ");
  if (!escrito) return "";
  const q = tokens(escrito);
  if (!q.length) return escrito.slice(0, 80);
  const mismos = EMPRESAS.filter((empresa) => {
    const t = tokens(empresa);
    if (t.length !== q.length) return false;
    const usados = new Set<number>();
    return q.every((token) => {
      const i = t.findIndex((otro, idx) => !usados.has(idx) && cerca(token, otro));
      if (i < 0) return false;
      usados.add(i);
      return true;
    });
  });
  if (mismos.length === 1) return mismos[0];
  return escrito.slice(0, 80);
}

export function acercarEmpresa(value: string) {
  const oficial = unificarEmpresa(value);
  if ((EMPRESAS as readonly string[]).includes(oficial)) return oficial;
  const q = tokens(value).join("");
  if (q.length < 6) return "";
  const hits = EMPRESAS.filter((empresa) => {
    const compacto = tokens(empresa).join("");
    if (Math.abs(compacto.length - q.length) > 2) return false;
    return compacto === q || dist(compacto, q) <= 2;
  });
  return hits.length === 1 ? hits[0] : "";
}

export function buscarEmpresas(q: string) {
  const plano = q.trim().normalize("NFD").replace(/\p{Diacritic}/gu, "").toUpperCase();
  if (!plano) return [...EMPRESAS];
  return EMPRESAS.filter((empresa) => empresa.normalize("NFD").replace(/\p{Diacritic}/gu, "").toUpperCase().includes(plano));
}
